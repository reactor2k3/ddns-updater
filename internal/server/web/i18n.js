function uiText(source) {
  if (currentLanguage === "de") return source;
  if (EN[source]) return EN[source];
  let match;
  if ((match = source.match(/^Hilfe: (.+)$/)))
    return `Help: ${uiText(match[1])}`;
  if ((match = source.match(/^(.+) (anzeigen|verbergen)$/)))
    return `${match[2] === "anzeigen" ? "Show" : "Hide"} ${uiText(match[1])}`;
  if ((match = source.match(/^(.+) bearbeiten$/))) return `Edit ${match[1]}`;
  if ((match = source.match(/^(IPv[46]) (aktiv|inaktiv)$/)))
    return `${match[1]} ${match[2] === "aktiv" ? "active" : "inactive"}`;
  if ((match = source.match(/^So geht’s bei (.+)$/)))
    return `Getting started with ${uiText(match[1])}`;
  if ((match = source.match(/^(\d+) von (\d+) Anbietern$/)))
    return `${match[1]} of ${match[2]} providers`;
  if ((match = source.match(/^über (\d+) Provider$/)))
    return `across ${match[1]} providers`;
  if ((match = source.match(/^(\d+) Eintr(?:ag|äge)(?: von (\d+))?$/)))
    return `${match[1]} ${match[1] === "1" ? "record" : "records"}${match[2] ? " of " + match[2] : ""}`;
  if (
    (match = source.match(/^vor (\d+) (Minute|Minuten|Stunde|Stunden|Sek\.)$/))
  ) {
    const unit = match[2].startsWith("Minute")
      ? "minute"
      : match[2].startsWith("Stunde")
        ? "hour"
        : "second";
    return `${match[1]} ${unit}${match[1] === "1" ? "" : "s"} ago`;
  }
  if (source === "gerade eben") return "just now";
  if ((match = source.match(/^Geprüft um (.+)$/)))
    return `Checked at ${match[1]}`;
  if ((match = source.match(/^Zuletzt erreichbar um (.+)$/)))
    return `Last connected at ${match[1]}`;
  if (
    (match = source.match(
      /^Öffne die DNS- oder DynDNS-Verwaltung bei (.+)\. Richte dort deinen Host ein und halte die unten aufgeführten Zugangsdaten bereit\. Die Anleitung zeigt die Schritte für diesen Anbieter\.$/,
    ))
  )
    return `Open the DNS or dynamic DNS settings at ${match[1]}. Set up your host and have the credentials listed below ready. The instructions explain the steps for this provider.`;
  if ((match = source.match(/^„(.+)“ aus der Vorschau löschen\?$/)))
    return `Remove “${match[1]}” from the preview?`;
  if (
    (match = source.match(
      /^„(.+)“ löschen\? Der DNS-Eintrag beim Provider bleibt bestehen\.$/,
    ))
  )
    return `Delete “${match[1]}”? The DNS record at your provider will remain.`;
  if (
    (match = source.match(
      /^Für (.+) muss der Hostname auf (.+) enden\. Beispiel: (.+)$/,
    ))
  )
    return `For ${match[1]}, the hostname must end in ${match[2]}. Example: ${match[3]}`;
  return source;
}
